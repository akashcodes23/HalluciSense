"""Phase 6J — Descriptive statistics per feature.

Computes comprehensive per-feature summary statistics across development
and validation matrices generated by Phase 6I. All computations are
NaN/Inf-safe and never modify input data.

Exported artifact: ``feature_statistics.json``

This module is analysis-only. It never modifies feature values.
"""

from __future__ import annotations

import json
import math
from dataclasses import dataclass, field, asdict
from pathlib import Path
from typing import Any, Dict, List, Optional

import numpy as np
from scipy import stats as scipy_stats
import structlog
from evaluation.phase6j.utils import _serializable

logger = structlog.get_logger(__name__)


# =========================================================
# DATA CLASSES
# =========================================================

@dataclass
class FeatureStatistics:
    """Comprehensive descriptive statistics for a single feature column.

    All fields default to safe sentinel values so that partial computation
    (e.g. on a constant or all-NaN column) never raises.
    """

    name: str

    # Counts
    count: int = 0
    nan_count: int = 0
    pos_inf_count: int = 0
    neg_inf_count: int = 0
    unique_count: int = 0

    # Central tendency
    mean: float = 0.0
    median: float = 0.0

    # Dispersion
    variance: float = 0.0
    std: float = 0.0
    min: float = 0.0
    max: float = 0.0
    abs_max: float = 0.0
    iqr: float = 0.0
    coefficient_of_variation: Optional[float] = None

    # Percentiles
    p1: float = 0.0
    p5: float = 0.0
    p25: float = 0.0
    p50: float = 0.0
    p75: float = 0.0
    p95: float = 0.0
    p99: float = 0.0
    p999: float = 0.0

    # Shape
    skewness: float = 0.0
    kurtosis: float = 0.0

    # Information
    entropy: float = 0.0

    # Validity
    is_valid: bool = True
    invalid_reason: str = ""


@dataclass
class SplitStatistics:
    """Statistics report for a single data split (development or validation)."""

    split_name: str = ""
    n_samples: int = 0
    n_positive: int = 0
    n_negative: int = 0
    feature_count: int = 0
    features: Dict[str, FeatureStatistics] = field(default_factory=dict)
    invalid_features: List[str] = field(default_factory=list)


@dataclass
class StatisticsReport:
    """Aggregated statistics report covering both splits."""

    development: Optional[SplitStatistics] = None
    validation: Optional[SplitStatistics] = None
    feature_names: List[str] = field(default_factory=list)
    feature_count: int = 0


# =========================================================
# PURE COMPUTATION FUNCTIONS
# =========================================================

def _safe_finite(col: np.ndarray) -> np.ndarray:
    """Extract the finite (non-NaN, non-Inf) elements of a 1-D array.

    Args:
        col: 1-D numpy array, possibly containing NaN and ±Inf.

    Returns:
        1-D numpy array with only finite values. May be empty.
    """
    return col[np.isfinite(col)]


def _compute_entropy(col_finite: np.ndarray, n_bins: int = 50) -> float:
    """Estimate Shannon entropy of a continuous feature via histogram binning.

    Uses numpy histogram with ``n_bins`` equal-width bins.  Empty or
    constant columns return 0.0.

    Args:
        col_finite: 1-D array of finite values.
        n_bins: Number of histogram bins (default 50).

    Returns:
        Shannon entropy in nats. Returns 0.0 for degenerate inputs.
    """
    if len(col_finite) < 2:
        return 0.0

    counts, _ = np.histogram(col_finite, bins=n_bins)
    # Normalise to probabilities, ignoring empty bins
    probs = counts[counts > 0] / counts.sum()
    if len(probs) <= 1:
        return 0.0

    return float(-np.sum(probs * np.log(probs)))


def compute_single_feature(
    col: np.ndarray,
    feature_name: str,
) -> FeatureStatistics:
    """Compute all descriptive statistics for one feature column.

    This function is pure: it does not modify ``col`` and has no side
    effects beyond the returned dataclass.

    Args:
        col: 1-D numpy array for the feature, may contain NaN/±Inf.
        feature_name: Human-readable name of the feature.

    Returns:
        Fully populated FeatureStatistics dataclass.  If the column is
        entirely NaN/Inf the ``is_valid`` flag is set to False and safe
        defaults are returned.
    """
    fs = FeatureStatistics(name=feature_name)
    fs.count = int(len(col))

    # --- Counts of invalid values ---
    fs.nan_count = int(np.isnan(col).sum())
    fs.pos_inf_count = int(np.isposinf(col).sum())
    fs.neg_inf_count = int(np.isneginf(col).sum())

    # --- Finite subset ---
    finite = _safe_finite(col)

    if len(finite) == 0:
        fs.is_valid = False
        fs.invalid_reason = "all values are NaN or Inf"
        logger.warning(
            "phase6j_invalid_feature",
            feature=feature_name,
            reason=fs.invalid_reason,
        )
        return fs

    fs.unique_count = int(len(np.unique(finite)))

    # --- Central tendency ---
    fs.mean = float(np.mean(finite))
    fs.median = float(np.median(finite))

    # --- Dispersion ---
    fs.variance = float(np.var(finite, ddof=0))
    fs.std = float(np.std(finite, ddof=0))
    fs.min = float(np.min(finite))
    fs.max = float(np.max(finite))
    fs.abs_max = float(np.max(np.abs(finite)))

    # --- Percentiles ---
    percentiles = np.percentile(finite, [1, 5, 25, 50, 75, 95, 99, 99.9])
    fs.p1 = float(percentiles[0])
    fs.p5 = float(percentiles[1])
    fs.p25 = float(percentiles[2])
    fs.p50 = float(percentiles[3])
    fs.p75 = float(percentiles[4])
    fs.p95 = float(percentiles[5])
    fs.p99 = float(percentiles[6])
    fs.p999 = float(percentiles[7])

    # --- Interquartile range ---
    fs.iqr = float(fs.p75 - fs.p25)

    # --- Coefficient of variation ---
    if abs(fs.mean) > 1e-15:
        fs.coefficient_of_variation = float(fs.std / abs(fs.mean))
    else:
        fs.coefficient_of_variation = None

    # --- Shape: skewness and kurtosis ---
    if fs.std > 1e-15 and len(finite) >= 3:
        fs.skewness = float(scipy_stats.skew(finite, bias=False))
    else:
        fs.skewness = 0.0

    if fs.std > 1e-15 and len(finite) >= 4:
        # Fisher kurtosis (excess kurtosis, normal = 0)
        fs.kurtosis = float(scipy_stats.kurtosis(finite, bias=False, fisher=True))
    else:
        fs.kurtosis = 0.0

    # --- Information: entropy ---
    fs.entropy = _compute_entropy(finite)

    # --- Validity check ---
    if fs.unique_count <= 1:
        fs.is_valid = False
        fs.invalid_reason = "constant column (zero variance)"
        logger.warning(
            "phase6j_invalid_feature",
            feature=feature_name,
            reason=fs.invalid_reason,
        )

    return fs


def compute_split_statistics(
    X: np.ndarray,
    y: np.ndarray,
    feature_names: List[str],
    split_name: str,
) -> SplitStatistics:
    """Compute descriptive statistics for every feature in one data split.

    This function is pure: it does not modify inputs and has no I/O side
    effects.

    Args:
        X: Feature matrix of shape (n_samples, n_features).
        y: Binary label array of shape (n_samples,).
        feature_names: Ordered list of feature column names.
        split_name: Human-readable name of the split (e.g. 'development').

    Returns:
        SplitStatistics with per-feature results.

    Raises:
        ValueError: If X.shape[1] != len(feature_names).
    """
    if X.shape[1] != len(feature_names):
        raise ValueError(
            f"Feature count mismatch: X has {X.shape[1]} columns "
            f"but {len(feature_names)} names were provided."
        )

    split = SplitStatistics(
        split_name=split_name,
        n_samples=int(X.shape[0]),
        n_positive=int((y == 1).sum()),
        n_negative=int((y == 0).sum()),
        feature_count=len(feature_names),
    )

    for idx, name in enumerate(feature_names):
        col = X[:, idx].astype(float)
        fs = compute_single_feature(col, name)
        split.features[name] = fs
        if not fs.is_valid:
            split.invalid_features.append(name)

    return split


# =========================================================
# PUBLIC API
# =========================================================

def compute_statistics(
    X_dev: np.ndarray,
    y_dev: np.ndarray,
    X_val: np.ndarray,
    y_val: np.ndarray,
    feature_names: List[str],
    out_dir: Path,
) -> StatisticsReport:
    """Compute descriptive statistics for development and validation splits.

    This is the single public entry point for the statistics module.
    It analyses both feature matrices, exports a JSON report, and
    returns the aggregated results.

    Args:
        X_dev: Development feature matrix, shape (n_dev, n_features).
        y_dev: Development labels, shape (n_dev,).
        X_val: Validation feature matrix, shape (n_val, n_features).
        y_val: Validation labels, shape (n_val,).
        feature_names: Ordered list of feature column names.
        out_dir: Directory to write ``feature_statistics.json``.

    Returns:
        StatisticsReport containing results for both splits.
    """
    logger.info(
        "phase6j_statistics_start",
        n_dev=X_dev.shape[0],
        n_val=X_val.shape[0],
        n_features=len(feature_names),
    )

    dev_stats = compute_split_statistics(X_dev, y_dev, feature_names, "development")
    val_stats = compute_split_statistics(X_val, y_val, feature_names, "validation")

    report = StatisticsReport(
        development=dev_stats,
        validation=val_stats,
        feature_names=list(feature_names),
        feature_count=len(feature_names),
    )

    # --- Export ---
    out_dir.mkdir(parents=True, exist_ok=True)
    out_path = out_dir / "feature_statistics.json"
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(_serializable(asdict(report)), f, indent=2)

    # --- Log summary ---
    n_invalid_dev = len(dev_stats.invalid_features)
    n_invalid_val = len(val_stats.invalid_features)
    logger.info(
        "phase6j_statistics_complete",
        output=str(out_path),
        dev_invalid=n_invalid_dev,
        val_invalid=n_invalid_val,
    )

    return report
